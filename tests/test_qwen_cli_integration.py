class RecordingTextGenerator:
    """Local fake generator for integration tests; it never opens a network connection."""

    def __init__(self, config=None, timeout_seconds: float = 60.0):
        self.config = config
        self.timeout_seconds = timeout_seconds
        self.generated_inputs = []
        self._last_metadata = None
        self._pending_calls = []

    def generate(
        self,
        record_label: str,
        entity_type: str,
        relation: str,
        angle: str,
        facts: list[str],
    ) -> str:
        self.generated_inputs.append(
            {
                "record_label": record_label,
                "entity_type": entity_type,
                "relation": relation,
                "angle": angle,
                "facts": list(facts),
            }
        )
        text = f"{record_label} generated by fake Qwen from {relation}."
        metadata = {
            "generator": "qwen2_vl_7b",
            "model_name": getattr(self.config, "model_name", "./Qwen/Qwen2-VL-7B-Instruct"),
            "model_status": "generated",
            "fallback_used": False,
            "candidate_text": text,
        }
        self._last_metadata = metadata
        self._pending_calls.append(
            {
                "metadata": dict(metadata),
                "provider": "qwen-local-openai-compatible",
                "model_name": metadata["model_name"],
                "base_url": getattr(self.config, "base_url", "http://fake-qwen.test/v1"),
                "temperature": getattr(self.config, "temperature", 0.1),
                "max_tokens": getattr(self.config, "max_token", 128),
                "prompt": f"fake prompt for {record_label} / {relation}",
                "response_text": text,
                "latency_ms": 1,
                "status": "generated",
                "error": None,
                "fallback_used": False,
            }
        )
        return text

    def last_candidate_metadata(self) -> dict:
        return dict(self._last_metadata)

    def consume_last_call(self, entity_key: str, candidate_id: str) -> dict | None:
        if not self._pending_calls:
            return None
        row = dict(self._pending_calls.pop())
        row["entity_key"] = entity_key
        row["candidate_id"] = candidate_id
        return row


class OptionalHookTextGenerator:
    def __init__(
        self,
        metadata=None,
        call=None,
        metadata_error: Exception | None = None,
        call_error: Exception | None = None,
    ):
        self.metadata = metadata
        self.call = call
        self.metadata_error = metadata_error
        self.call_error = call_error

    def generate(
        self,
        record_label: str,
        entity_type: str,
        relation: str,
        angle: str,
        facts: list[str],
    ) -> str:
        return f"{record_label} optional-hook text for {relation}."

    def last_candidate_metadata(self):
        if self.metadata_error is not None:
            raise self.metadata_error
        return self.metadata

    def consume_last_call(self, entity_key: str, candidate_id: str):
        if self.call_error is not None:
            raise self.call_error
        return self.call


