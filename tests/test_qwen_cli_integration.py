def test_cli_qwen_local_writes_safe_config_and_model_calls(tmp_path, monkeypatch):
    dataset_dir = make_fixture(tmp_path / "dataset")
    output_root = tmp_path / "outputs"
    config_path = tmp_path / "qwen.yaml"
    config_path.write_text("fake config is loaded through monkeypatch\n", encoding="utf-8")
    qwen_config = SimpleNamespace(
        model_name="./Qwen/Qwen2-VL-7B-Instruct",
        base_url="http://localhost:8000/v1",
        api_key="secret-token",
        max_token=192,
        temperature=0.2,
    )
    loaded_paths = []
    generators = []

    def fake_load_config(path):
        loaded_paths.append(Path(path))
        return qwen_config

    class FakeQwenLocalTextGenerator(RecordingTextGenerator):
        def __init__(self, config, timeout_seconds: float = 60.0):
            super().__init__(config=config, timeout_seconds=timeout_seconds)
            generators.append(self)

    monkeypatch.setattr(run_module, "load_qwen_config", fake_load_config, raising=False)
    monkeypatch.setattr(run_module, "QwenLocalTextGenerator", FakeQwenLocalTextGenerator, raising=False)

    main(
        [
            "--dataset-dir",
            str(dataset_dir),
            "--missing-mode",
            "text",
            "--limit",
            "1",
            "--candidate-budget",
            "2",
            "--output-root",
            str(output_root),
            "--run-name",
            "qwen_cli",
            "--text-generator",
            "qwen-local",
            "--stage02-planner",
            "rule",
            "--stage3-planner",
            "rule",
            "--stage4-ranker",
            "legacy",
            "--stage3-scorer",
            "rule-weighted",
            "--stage3-llm-assessor",
            "none",
            "--model-config",
            str(config_path),
            "--model-call-timeout-seconds",
            "7",
        ]
    )

    assert loaded_paths == [config_path]
    assert len(generators) == 1
    assert generators[0].timeout_seconds == 7

    run_dir = output_root / "qwen_cli"
    config = json.loads((run_dir / "config.json").read_text(encoding="utf-8"))
    config_text = (run_dir / "config.json").read_text(encoding="utf-8")
    assert config["text_generator"] == "qwen-local"
    assert config["model_config"] == str(config_path)
    assert config["model_name"] == "./Qwen/Qwen2-VL-7B-Instruct"
    assert config["base_url"] == "http://localhost:8000/v1"
    assert config["api_key_configured"] is True
    assert "api_key" not in config
    assert "secret-token" not in config_text

    rows = _jsonl_rows(run_dir / "entities" / "Q1" / "model_calls.jsonl")
    assert len(rows) == 2
    assert [row["status"] for row in rows] == ["generated", "generated"]
